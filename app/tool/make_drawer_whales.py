#!/usr/bin/env python3
"""Generates lib/ui/shell/drawer/happening_whales.dart: the 正在发生 rows'
still whales (the live activity's compact frames, @2x: 48 × 32 cells drawn
in a 24 × 16 dp box) as const pixel rows, so they draw on the first frame
with no image to decode (goldens never catch one half-loaded).

  python3 -I app/tool/make_drawer_whales.py <dir with compact-<state>@2x.png>

The source is plan/design/live-activity-a/assets/ of the design hand-off.
Stdlib only (8-bit RGBA PNG).
"""

import struct
import sys
import zlib
from pathlib import Path

STATES = ['swim', 'approval', 'question', 'done', 'failed', 'multi']
OUT = Path(__file__).resolve().parent.parent / 'lib/ui/shell/drawer/happening_whales.dart'
CELLS = '0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ'


def load(path):
    data = path.read_bytes()
    i, idat = 8, b''
    while i < len(data):
        (length,) = struct.unpack('>I', data[i:i + 4])
        kind, chunk = data[i + 4:i + 8], data[i + 8:i + 8 + length]
        if kind == b'IHDR':
            w, h, depth, color = struct.unpack('>IIBB', chunk[:10])
            assert depth == 8 and color == 6, f'{path}: 8-bit RGBA expected'
        elif kind == b'IDAT':
            idat += chunk
        i += 12 + length
    raw, bpp = zlib.decompress(idat), 4
    stride, prev, rows = w * bpp + 1, bytearray(w * bpp), []
    for y in range(h):
        f, line = raw[y * stride], bytearray(raw[y * stride + 1:(y + 1) * stride])
        for x in range(len(line)):
            a = line[x - bpp] if x >= bpp else 0
            b = prev[x]
            c = prev[x - bpp] if x >= bpp else 0
            if f == 1:
                line[x] = (line[x] + a) & 255
            elif f == 2:
                line[x] = (line[x] + b) & 255
            elif f == 3:
                line[x] = (line[x] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[x] = (line[x] + (a if pa <= pb and pa <= pc else (b if pb <= pc else c))) & 255
        prev = line
        rows.append([tuple(line[x * bpp:(x + 1) * bpp]) for x in range(w)])
    return w, h, rows


def main():
    src = Path(sys.argv[1])
    palette, frames = [], {}
    size = None
    for state in STATES:
        w, h, rows = load(src / f'compact-{state}@2x.png')
        assert size in (None, (w, h)), 'frames differ in size'
        size = (w, h)
        lines = []
        for row in rows:
            cells = []
            for r, g, b, a in row:
                if a < 16:  # stray edge noise, not ink
                    cells.append('.')
                    continue
                argb = (a << 24) | (r << 16) | (g << 8) | b
                if argb not in palette:
                    palette.append(argb)
                cells.append(CELLS[palette.index(argb)])
            lines.append(''.join(cells))
        frames[state] = lines
    assert len(palette) <= len(CELLS)
    w, h = size
    out = [
        '// GENERATED by tool/make_drawer_whales.py from the live activity\'s',
        '// compact frames (@2x). Do not edit; run the tool.',
        '',
        '/// Cells per row and rows per frame ($w × $h, drawn in half-dp cells).'.replace('$w', str(w)).replace('$h', str(h)),
        f'const int happeningWhaleWidth = {w};',
        f'const int happeningWhaleHeight = {h};',
        '',
        '/// ARGB colours; a frame cell is an index into this list (`.`: none).',
        'const List<int> happeningWhalePalette = [',
        *[f'  0x{c:08X},' for c in palette],
        '];',
        '',
        '/// Index characters of [happeningWhalePalette].',
        f"const String happeningWhaleCells = '{CELLS}';",
        '',
        '/// One still frame per state, rows top to bottom.',
        'const Map<String, List<String>> happeningWhaleFrames = {',
    ]
    for state, lines in frames.items():
        out.append(f"  '{state}': [")
        out.extend(f"    '{line}'," for line in lines)
        out.append('  ],')
    out.append('};')
    OUT.write_text('\n'.join(out) + '\n', encoding='utf-8')
    print(f'{OUT}: {len(frames)} frames, {len(palette)} colours')


if __name__ == '__main__':
    main()
